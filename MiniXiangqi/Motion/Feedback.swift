// Feedback for an event fires when the event completes: a move sounds when the
// piece lands. The 声音 and 触感 switches each gate their own half; neither
// knows the other.

import SwiftUI

/// What is heard. The felt half is `boardHaptics`, triggered by the counts the
/// board's motion object keeps.
struct Feedback {
    /// One per landing. Every case is an event of the board: nothing sounds for
    /// an illegal tap, a refusal, a selection or a flip, since a noise would
    /// scold a learner's exploratory tap.
    enum Sound: String, CaseIterable, Equatable {
    /// A disc meeting the board.
        case plain
        /// The same landing with mass behind it.
        case capture
        /// The landing, plus the accent that sounds with the check rings.
        case check
    /// A result, including a draw claimed without any piece moving.
        case conclusion
    /// A stone meeting the board: sharper and smaller than a disc, since it
    /// arrives without travelling.
        case stone

    /// Generated by `Sounds/generate.py`; the prefix keeps the samples together
    /// in a resource directory that has no folders.
        var resource: String { "board-\(rawValue)" }

    /// One sound, chosen by what has arrived:
    /// - The game being over replaces the landing sound: a tock underneath the
    ///   result would compete with it.
    /// - A capture outranks a check: the check also has the rings, the 将军
    ///   token and the status line.
    /// - Everything else is the plain tock, an undo included.
    ///
    /// Only a move's fading disc is a capture; a reversal's is a piece coming
    /// back. The rule reads a position, not an action, so replay asks it too.
    /// `stone` is a parameter because a placement builds no transit.
        static func ofTheLanding(_ transit: Transit?,
                                 stone: Bool = false,
                                 finished: Bool,
                                 inCheck: Bool) -> Sound {
            if finished { return .conclusion }
            if transit?.kind == .move, transit?.fading != nil { return .capture }
            if inCheck { return .check }
            return stone ? .stone : .plain
        }
    }

    var play: (Sound) -> Void

    /// Loaded once so the first landing is no later than the second.
    static let live: Feedback = {
        let sounds = BoardSounds()
        return Feedback { sound in
            guard UserDefaults.standard.object(forKey: "sound.enabled") as? Bool ?? true
            else { return }
            sounds.play(sound)
        }
    }()
}

extension View {
    /// The felt half: one pattern for every landing, the lightest one for a
    /// touch the game cannot act on, behind the 触感 switch. A capture, a check
    /// and a result change what is heard and not what is felt.
    func boardHaptics(landings: Int, refusals: Int = 0) -> some View {
        modifier(BoardHaptics(landings: landings, refusals: refusals))
    }
}

private struct BoardHaptics: ViewModifier {
    var landings: Int
    var refusals: Int
    @AppStorage("haptics.enabled") private var enabled = true

    func body(content: Content) -> some View {
        content
            .sensoryFeedback(Self.landing, trigger: landings) { _, _ in enabled }
            .sensoryFeedback(Self.refusal, trigger: refusals) { _, _ in enabled }
    }

    #if os(macOS)
    private static let landing = SensoryFeedback.alignment
    private static let refusal = SensoryFeedback.levelChange
    #else
    private static let landing = SensoryFeedback.impact(flexibility: .rigid)
    private static let refusal = SensoryFeedback.selection
    #endif
}
