// What the board gives back: a sound per landing, and a haptic per landing and
// per touch the game cannot act on.
//
// docs/interaction-design.md, "Sound and haptics": feedback that reports an
// event fires when the event completes — a move sounds when the piece lands —
// and an illegal tap takes the platform's lightest feedback, never a warning.
// The 声音 and 触感 switches each gate their own half; neither knows the other.

import SwiftUI

/// What is heard. The felt half is `boardHaptics`, triggered by the counts the
/// board's motion object keeps.
struct Feedback {
    /// What is heard. One per landing and never more, chosen by what the
    /// landing means rather than by how often it happens: conclusion, then
    /// capture, then check, then the plain arrival. A capturing check is a
    /// capture — the take is the louder fact, and the rings say the rest.
    ///
    /// Every case is an event of the *board*. There is nothing here for an
    /// illegal tap, a refusal, a selection, or a flip: sound reinforces
    /// meaning, and answering a learner's exploratory tap with a noise would
    /// scold it. Those keep the lightest haptic and their answer on the board.
    enum Sound: String, CaseIterable, Equatable {
        /// A disc meeting the board. The one every move makes.
        case plain
        /// The same landing with mass behind it.
        case capture
        /// The landing, plus the accent that sounds with the check rings.
        case check
        /// The game settling — a result, however it was reached, including the
        /// draw a player claims without any piece moving at all.
        case conclusion
        /// A stone meeting the board. The placement games' one landing, and a
        /// sharper, smaller sound than the disc's: a stone is a harder, lighter
        /// thing than a wooden disc and it arrives without travelling.
        case stone

        /// The sample in the app bundle. Generated by `Sounds/generate.py`
        /// and by nothing else; the prefix keeps the five together in a
        /// resource directory that has no folders.
        var resource: String { "board-\(rawValue)" }

        /// What a landing sounds like: one sound, chosen by what has arrived
        /// rather than by what was pressed, in the accepted order of
        /// precedence.
        ///
        /// - The game being over outranks everything, and replaces the landing
        ///   sound rather than joining it: a result is the last thing that
        ///   happened, and a tock underneath it would be the move competing
        ///   with its own consequence.
        /// - A capture outranks a check, because the take is the louder fact
        ///   and the check has the rings, the 将军 token, and the status line
        ///   saying it as well.
        /// - Everything else is the plain tock, a move taken back included:
        ///   reversing a move is a disc landing on a point, and a sound played
        ///   backwards would be a fifth thing to learn for an action the board
        ///   already animates in reverse.
        ///
        /// It reads the arrived position and the transit's own plan, both of
        /// which are settled before anything can arrive. A capture is the
        /// transit's fading disc — but only a move's, since a reversal's
        /// fading disc is the piece coming *back*, which is a restoration and
        /// not a take.
        ///
        /// One rule, and it describes a position rather than an action, which
        /// is why replay asks it the same question: a replayed landing is a
        /// landing, and the position it arrives at is finished or in check or
        /// neither exactly as a played one's is.
        /// `stone` says the landing was a stone placed rather than a disc
        /// arriving. It is a parameter rather than a fifth thing read off the
        /// transit because a placement builds no transit at all: nothing
        /// travels, so the landing is the commit itself.
        static func ofTheLanding(_ transit: Transit?,
                                 stone: Bool = false,
                                 finished: Bool,
                                 inCheck: Bool) -> Sound {
            if finished { return .conclusion }
            if transit?.kind == .move, transit?.fading != nil { return .capture }
            if inCheck { return .check }
            return stone ? .stone : .plain
        }
    }

    var play: (Sound) -> Void

    /// The board's samples, loaded once so the first landing is no later than
    /// the second, behind the 声音 switch.
    static let live: Feedback = {
        let sounds = BoardSounds()
        return Feedback { sound in
            guard UserDefaults.standard.object(forKey: "sound.enabled") as? Bool ?? true
            else { return }
            sounds.play(sound)
        }
    }()
}

extension View {
    /// The felt half: one pattern for every landing, the lightest one for a
    /// touch the game cannot act on, behind the 触感 switch. A capture, a check
    /// and a result change what is heard and not what is felt.
    func boardHaptics(landings: Int, refusals: Int = 0) -> some View {
        modifier(BoardHaptics(landings: landings, refusals: refusals))
    }
}

private struct BoardHaptics: ViewModifier {
    var landings: Int
    var refusals: Int
    @AppStorage("haptics.enabled") private var enabled = true

    func body(content: Content) -> some View {
        content
            .sensoryFeedback(Self.landing, trigger: landings) { _, _ in enabled }
            .sensoryFeedback(Self.refusal, trigger: refusals) { _, _ in enabled }
    }

    #if os(macOS)
    private static let landing = SensoryFeedback.alignment
    private static let refusal = SensoryFeedback.levelChange
    #else
    private static let landing = SensoryFeedback.impact(flexibility: .rigid)
    private static let refusal = SensoryFeedback.selection
    #endif
}
